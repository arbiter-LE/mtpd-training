#!/usr/bin/env node
// Registry dates parse in local time; pin to the agencies' zone so results match on any machine.
process.env.TZ = 'America/New_York';
/* ──────────────────────────────────────────────────────────────────────
   Department content bundle build.

   Module content (reading, scenarios, quiz questions, supervisor
   overlays) and each agency's reference content (admin Legal Citations
   tab + agency glossary entries, which quote its orders) must never be
   served as public static files: js/modules/ is in .vercelignore. This
   script bundles each registered department's moduleScripts (in order)
   plus its referenceFile into api/_bundle/departments.js, which only
   the /api/content function can read. That function hands a department's
   bundle to a signed-in officer of that department, and to nobody else.

   Run after ANY change under js/modules/ or to a registry entry's
   moduleScripts / referenceFile / Supabase settings. The smoke test
   (and so the pre-commit hook) fails if the bundle is out of date.

   Usage:  node _dev/build-content.js          (writes the bundle)
           require('./build-content').render() (smoke test: expected text)
   ────────────────────────────────────────────────────────────────────── */
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const crypto = require('crypto');
const ROOT = path.resolve(__dirname, '..');
const OUT_FILE = path.join(ROOT, 'api/_bundle/departments.js');
const REGIONS = ['citations', 'glossary-terms', 'glossary-sops'];

function loadRegistry() {
  const ctx = { window: { location: { hostname: '', search: '' } },
                document: { documentElement: { setAttribute() {} }, querySelectorAll: () => [] } };
  ctx.globalThis = ctx; vm.createContext(ctx);
  const src = fs.readFileSync(path.join(ROOT, 'js/departments/registry.js'), 'utf8');
  vm.runInContext(src + ';globalThis.__REG = DEPARTMENT_REGISTRY;', ctx);
  return ctx.__REG;
}

// Split a reference file into its named regions. Each region's HTML is
// passed through untouched; it is injected at the matching
// data-dept-slot element in index.html.
function parseReference(text, rel) {
  const out = {};
  const re = /<!-- @region ([a-z-]+) -->\n([\s\S]*?)\n?<!-- @endregion -->/g;
  let m;
  while ((m = re.exec(text))) {
    if (!REGIONS.includes(m[1])) throw new Error(`${rel}: unknown region "${m[1]}"`);
    out[m[1]] = m[2];
  }
  return out;
}

function bundleFor(dept) {
  const scripts = dept.moduleScripts.map(rel => {
    const abs = path.join(ROOT, rel);
    if (!fs.existsSync(abs)) throw new Error(`${dept.subdomain}: missing moduleScript ${rel}`);
    return { src: rel, code: fs.readFileSync(abs, 'utf8') };
  });
  let reference = {};
  if (dept.referenceFile) {
    const abs = path.join(ROOT, dept.referenceFile);
    if (!fs.existsSync(abs)) throw new Error(`${dept.subdomain}: missing referenceFile ${dept.referenceFile}`);
    reference = parseReference(fs.readFileSync(abs, 'utf8'), dept.referenceFile);
  }
  const body = JSON.stringify({ department: dept.subdomain, scripts, reference });
  const version = crypto.createHash('sha256').update(body).digest('hex').slice(0, 20);
  return { version, body };
}

function render() {
  const registry = loadRegistry();
  const content = {};
  const auth = {};
  for (const d of registry) {
    content[d.subdomain] = bundleFor(d);
    auth[d.subdomain] = { url: d.supabaseUrl, anonKey: d.supabaseKey };
  }
  return [
    '// AUTO-GENERATED by _dev/build-content.js — do not edit by hand.',
    '// Department content bundles, readable only by api/content.js (files under',
    '// api/_* are neither public URLs nor functions). Source of truth: the',
    '// files listed in each registry entry\'s moduleScripts + referenceFile.',
    '// The anon keys below are the same public keys shipped in registry.js.',
    'export const DEPT_AUTH = ' + JSON.stringify(auth) + ';',
    'export const CONTENT = ' + JSON.stringify(content) + ';',
    '',
  ].join('\n');
}

module.exports = { render, OUT_FILE, REGIONS, parseReference };

if (require.main === module) {
  try {
    const text = render();
    fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
    fs.writeFileSync(OUT_FILE, text);
    const sizes = Object.entries(JSON.parse(text.match(/CONTENT = (.*);\n/)[1]))
      .map(([k, v]) => `${k} ${(v.body.length / 1024).toFixed(0)} KB (v ${v.version})`);
    console.log('✓ wrote api/_bundle/departments.js — ' + sizes.join(' · '));
  } catch (e) {
    console.error('✗ ' + e.message);
    process.exit(1);
  }
}
